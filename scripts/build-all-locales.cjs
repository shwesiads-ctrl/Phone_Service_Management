const fs = require('fs');

const existing = fs.readFileSync('src/i18n/translations.ts', 'utf8');

function extractBlock(name) {
  const startMark = `${name}: {`;
  const startIdx = existing.indexOf(startMark);
  if (startIdx === -1) return null;
  let depth = 0;
  let endIdx = startIdx;
  for (let i = startIdx; i < existing.length; i++) {
    if (existing[i] === '{') depth++;
    else if (existing[i] === '}') {
      depth--;
      if (depth === 0) {
        endIdx = i + 1;
        break;
      }
    }
  }
  return existing.slice(startIdx, endIdx);
}

const enBlock = extractBlock('en');
const myBlock = extractBlock('my');
const thBlock = extractBlock('th');

const enObj = {};
enBlock.split('\n').forEach(line => {
  const m = line.match(/^\s*([a-zA-Z0-9_]+)\s*:\s*(['"`].*['"`]),?\s*$/);
  if (m) {
    try {
      enObj[m[1]] = eval(m[2]);
    } catch(e) {
      enObj[m[1]] = m[2].slice(1, -1);
    }
  }
});

